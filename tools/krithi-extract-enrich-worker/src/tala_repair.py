"""Compile explicitly reviewed tala evidence into an audited Flyway migration.

This module has no database or network client. Candidate output cannot be applied
directly: the review manifest requires a decision, identity and exact prior lyric.
"""

from __future__ import annotations

import json
import re
from datetime import date
from typing import Literal
from urllib.parse import urlsplit
from uuid import UUID

from pydantic import BaseModel, Field, field_validator, model_validator


class ReviewedTala(BaseModel):
    krithi_id: UUID
    title: str = Field(min_length=1)
    composer: str = Field(min_length=1)
    raga_id: UUID
    raga: str = Field(min_length=1)
    expected_tala: Literal["Unknown"]
    proposed_tala: str = Field(min_length=1)
    expected_pallavi: str = Field(min_length=15)
    source_name: str = Field(min_length=1)
    source_url: str
    source_checksum: str = Field(pattern=r"^[0-9a-f]{64}$")
    source_locator: str = Field(min_length=10)
    raw_tala: str = Field(min_length=1)
    source_pallavi: str = Field(min_length=10)
    reviewed_by: str = Field(min_length=3)
    reviewed_on: date
    decision: Literal["accepted"]

    @field_validator("source_url")
    @classmethod
    def public_https_source(cls, value: str) -> str:
        parsed = urlsplit(value)
        if parsed.scheme != "https" or not parsed.hostname or parsed.username or parsed.password:
            raise ValueError("Evidence needs an HTTPS source URL without credentials")
        return value

    @field_validator("proposed_tala")
    @classmethod
    def supported_tala(cls, value: str) -> str:
        # Expand only with an explicit musicological review; never accept damaged labels.
        if value not in {"Adi", "Rupaka", "Misra Capu", "Khanda Capu", "Triputa", "Jhampa", "Ata", "Ekam"}:
            raise ValueError("Tala is outside the reviewed canonical vocabulary")
        return value


class TalaRepairManifest(BaseModel):
    track: Literal["TRACK-144"]
    source_format: Literal["HTML", "PDF"] = "HTML"
    rows: list[ReviewedTala] = Field(min_length=1)

    @model_validator(mode="after")
    def unique_compositions(self) -> TalaRepairManifest:
        if len({r.krithi_id for r in self.rows}) != len(self.rows):
            raise ValueError("Duplicate composition decisions require conflict resolution")
        return self


def compile_migration(manifest: TalaRepairManifest, evidence_filename: str = "track144-tala-evidence.json") -> str:
    if not re.fullmatch(r"[a-zA-Z0-9_-]+\.json", evidence_filename):
        raise ValueError("Evidence filename must be a plain JSON basename")
    # JSON is embedded as a SQL string literal, not shell interpolation. Apostrophes
    # are doubled; Unicode, backslashes and newlines remain JSON encoded.
    payload = json.dumps([r.model_dump(mode="json") for r in manifest.rows], ensure_ascii=False).replace("'", "''")
    if "$track144$" in payload:
        raise ValueError("Manifest contains reserved SQL dollar delimiter")
    sql = (
        """-- corpus-data-fix: allow
-- TRACK-144: reviewed source-backed tala repairs. Generated by compile_tala_repairs.py.
-- Evidence: database/data/track144-tala-evidence.json. Never edit after application.
-- Missing corpus UUIDs are no-ops on reference-only installations; changed identities fail closed.
DO $track144$
DECLARE
    repair record;
    before_row krithis%ROWTYPE;
    after_row krithis%ROWTYPE;
    evidence_row krithi_source_evidence%ROWTYPE;
    target_tala uuid;
    source_id uuid;
BEGIN
    FOR repair IN SELECT * FROM jsonb_to_recordset('"""
        + payload
        + """'::jsonb) AS x(
        krithi_id uuid, title text, composer text, raga_id uuid, raga text,
        expected_tala text, proposed_tala text, expected_pallavi text,
        source_name text, source_url text, source_checksum text, source_locator text,
        raw_tala text, source_pallavi text, reviewed_by text, reviewed_on text, decision text
    ) LOOP
        SELECT * INTO before_row FROM krithis WHERE id = repair.krithi_id FOR UPDATE;
        IF NOT FOUND THEN CONTINUE; END IF;
        IF before_row.title <> repair.title OR before_row.primary_raga_id IS DISTINCT FROM repair.raga_id
           OR NOT EXISTS (SELECT 1 FROM composers WHERE id = before_row.composer_id AND name = repair.composer)
           OR NOT EXISTS (
               SELECT 1 FROM krithi_lyric_variants v
               JOIN krithi_lyric_sections ls ON ls.lyric_variant_id = v.id
               JOIN krithi_sections s ON s.id = ls.section_id AND s.krithi_id = v.krithi_id
               WHERE v.krithi_id = repair.krithi_id AND v.script = 'latin'
                 AND s.section_type = 'PALLAVI' AND ls.text = repair.expected_pallavi
           ) THEN
            RAISE EXCEPTION 'TRACK-144: changed composition identity/pallavi %', repair.krithi_id;
        END IF;
        SELECT id INTO STRICT target_tala FROM talas WHERE name = repair.proposed_tala;
        IF before_row.tala_id = target_tala THEN CONTINUE; END IF;
        IF NOT EXISTS (SELECT 1 FROM talas WHERE id = before_row.tala_id AND name = repair.expected_tala) THEN
            RAISE EXCEPTION 'TRACK-144: intervening tala edit %', repair.krithi_id;
        END IF;
        SELECT id INTO STRICT source_id FROM import_sources WHERE name = repair.source_name;
        UPDATE krithis SET tala_id = target_tala, updated_at = clock_timestamp()
        WHERE id = repair.krithi_id RETURNING * INTO after_row;
        INSERT INTO audit_log(entity_table, entity_id, action, diff, metadata)
        VALUES ('krithis', repair.krithi_id, 'UPDATE',
            jsonb_build_object('before', to_jsonb(before_row), 'after', to_jsonb(after_row)),
            to_jsonb(repair) || '{"track":"TRACK-144","method":"manual_source_verification"}'::jsonb);

        -- A distinct editorial observation; do not overwrite earlier extraction provenance.
        INSERT INTO krithi_source_evidence(
            krithi_id, import_source_id, source_url, source_format, extraction_method,
            checksum, contributed_fields, raw_extraction
        ) VALUES (
            repair.krithi_id, source_id, repair.source_url, 'HTML', 'MANUAL',
            repair.source_checksum, ARRAY['tala'],
            to_jsonb(repair) || '{"track":"TRACK-144","checksum_format":"cached UTF-8 HTML"}'::jsonb
        ) RETURNING * INTO evidence_row;
        INSERT INTO audit_log(entity_table, entity_id, action, diff, metadata)
        VALUES ('krithi_source_evidence', evidence_row.id, 'CREATE',
            jsonb_build_object('after', to_jsonb(evidence_row)), '{"track":"TRACK-144"}'::jsonb);
    END LOOP;
END $track144$;
"""
    )
    if manifest.source_format == "PDF":
        sql = sql.replace("'HTML', 'MANUAL'", "'PDF', 'MANUAL'").replace("cached UTF-8 HTML", "raw PDF bytes")
    return sql.replace(
        "-- Evidence: database/data/track144-tala-evidence.json.", f"-- Evidence: database/data/{evidence_filename}.", 1
    )
